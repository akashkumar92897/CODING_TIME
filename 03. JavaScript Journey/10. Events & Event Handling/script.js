// ---------- Click & dblclick ----------
let p = document.querySelector("p")
p.addEventListener("click", function () {
    p.style.color = "white";
    p.style.backgroundColor = "red";
})
function dblClick() {
    p.style.color = "black";
    p.style.backgroundColor = "blue";
}
p.addEventListener("dblclick", dblClick)
p.removeEventListener("dblclick", dblClick);

// ---------- input ----------

let input = document.querySelector("input");
input.addEventListener("input", function () {
    input.style.backgroundColor = "Magenta";
})
function details(dets) {
    if (dets.data !== null) {
        console.log(dets.data);
    }
}
input.addEventListener("input", details);

// ---------- change ----------

let deviceSelected = document.querySelector("select");
let device = document.querySelector("#device");
function deviceDetails(dets) {
    console.log(dets.target.value);
    device.textContent = `${dets.target.value} Selected`
}
deviceSelected.addEventListener("change", deviceDetails);

